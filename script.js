let currentLang = 'en';
let currentPage = 'home';

const modal = document.getElementById('portfolioModal');
const modalImage = document.getElementById('modalImage');
const modalTitle = document.getElementById('modalTitle');
const modalSubtitle = document.getElementById('modalSubtitle');
const modalDescription = document.getElementById('modalDescription');
const modalTools = document.getElementById('modalTools');
const modalClose = document.getElementById('modalClose');

function langSuffix(lang) { return lang === 'ru' ? 'Ru' : 'En'; }
function pickData(el, name) { return el.dataset[`${name}${langSuffix(currentLang)}`] || el.dataset[`${name}En`] || ''; }

function contactHTML() {
  const dict = translations[currentLang];
  return `
    <div>
      <div class="eyebrow">${dict.contactEyebrow}</div>
      <h2>${dict.contactTitle}</h2>
      <p>${dict.contactText}</p>
    </div>
    <div class="contact-actions">
      <a class="btn btn-primary" href="mailto:pavel.s.mudrov@gmail.com">pavel.s.mudrov@gmail.com</a>
      <a class="btn btn-secondary" href="https://t.me/wiseisguilty3D" target="_blank" rel="noopener">Telegram / blog</a>
      <a class="btn btn-secondary" href="https://www.instagram.com/wiseisguilty.3d" target="_blank" rel="noopener">Instagram / blog</a>
    </div>`;
}

function renderContactBlocks() {
  document.querySelectorAll('[data-contact-block]').forEach(block => { block.innerHTML = contactHTML(); });
}

function applyLanguage(lang) {
  currentLang = translations[lang] ? lang : 'en';
  const dict = translations[currentLang];
  document.documentElement.lang = currentLang;
  document.title = currentLang === 'ru' ? 'Павел Мудров — Junior 3D Artist' : 'Pavel Mudrov — Junior 3D Artist';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const active = btn.dataset.lang === currentLang;
    btn.classList.toggle('is-active', active);
    btn.setAttribute('aria-pressed', active ? 'true' : 'false');
  });
  renderContactBlocks();
}

function showPage(page, pushHash = true) {
  const nextPage = document.querySelector(`[data-page="${page}"]`) ? page : 'home';
  currentPage = nextPage;
  document.querySelectorAll('.page-panel').forEach(panel => panel.classList.toggle('is-active', panel.dataset.page === nextPage));
  document.querySelectorAll('[data-page-link]').forEach(link => link.classList.toggle('is-active', link.dataset.pageLink === nextPage));
  if (pushHash) history.replaceState(null, '', `#${nextPage}`);
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function openModal(source, image) {
  if (!modal || !modalImage || !image) return;
  modalImage.src = image.getAttribute('src');
  modalImage.alt = image.getAttribute('alt') || '';
  modalTitle.textContent = pickData(source, 'title');
  modalSubtitle.textContent = pickData(source, 'subtitle');
  modalDescription.textContent = pickData(source, 'desc');
  modalTools.textContent = source.dataset.tools || '';
  modal.classList.add('is-open');
  modal.setAttribute('aria-hidden', 'false');
  document.body.style.overflow = 'hidden';
}

function closeModal() {
  if (!modal) return;
  modal.classList.remove('is-open');
  modal.setAttribute('aria-hidden', 'true');
  document.body.style.overflow = '';
  modalImage.src = '';
}

document.querySelectorAll('[data-page-link]').forEach(link => {
  link.addEventListener('click', event => {
    event.preventDefault();
    showPage(link.dataset.pageLink);
  });
});

document.querySelectorAll('.lang-btn').forEach(btn => btn.addEventListener('click', () => {
  try { localStorage.setItem('site-language', btn.dataset.lang); } catch (error) {}
  applyLanguage(btn.dataset.lang);
}));

document.querySelectorAll('.portfolio-card').forEach(card => {
  card.addEventListener('click', () => openModal(card, card.querySelector('img')));
  card.addEventListener('keydown', event => {
    if (event.key === 'Enter' || event.key === ' ') {
      event.preventDefault();
      openModal(card, card.querySelector('img'));
    }
  });
});

document.querySelectorAll('.game-shot-card').forEach(card => card.addEventListener('click', () => openModal(card, card.querySelector('img'))));
modalClose?.addEventListener('click', closeModal);
document.querySelectorAll('[data-close-modal]').forEach(el => el.addEventListener('click', closeModal));
document.addEventListener('keydown', event => { if (event.key === 'Escape') closeModal(); });
window.addEventListener('hashchange', () => showPage(location.hash.replace('#', '') || 'home', false));

function detectInitialLanguage() {
  const params = new URLSearchParams(window.location.search);
  const urlLang = params.get('lang');
  if (urlLang === 'ru' || urlLang === 'en') return urlLang;

  try {
    const savedLang = localStorage.getItem('site-language');
    if (savedLang === 'ru' || savedLang === 'en') return savedLang;
  } catch (error) {}

  const browserLanguages = [navigator.language, ...(navigator.languages || [])]
    .filter(Boolean)
    .map(lang => lang.toLowerCase());
  const timezone = Intl.DateTimeFormat().resolvedOptions().timeZone || '';
  const russianTimezones = new Set([
    'Europe/Kaliningrad', 'Europe/Moscow', 'Europe/Kirov', 'Europe/Volgograd', 'Europe/Astrakhan', 'Europe/Saratov', 'Europe/Ulyanovsk',
    'Asia/Yekaterinburg', 'Asia/Omsk', 'Asia/Novosibirsk', 'Asia/Barnaul', 'Asia/Tomsk', 'Asia/Novokuznetsk', 'Asia/Krasnoyarsk',
    'Asia/Irkutsk', 'Asia/Chita', 'Asia/Yakutsk', 'Asia/Khandyga', 'Asia/Vladivostok', 'Asia/Ust-Nera', 'Asia/Magadan',
    'Asia/Sakhalin', 'Asia/Srednekolymsk', 'Asia/Kamchatka', 'Asia/Anadyr'
  ]);

  if (russianTimezones.has(timezone)) return 'ru';
  if (!timezone && browserLanguages.some(lang => lang === 'ru' || lang.startsWith('ru-'))) return 'ru';
  return 'en';
}

applyLanguage(detectInitialLanguage());
showPage(location.hash.replace('#', '') || 'home', false);
